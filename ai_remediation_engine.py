def _load_scan_report(params: dict) -> tuple[dict | None, str, str | None]:
    """Return (report_dict, target_label, error)."""
    if params.get("scan_report") and isinstance(params["scan_report"], dict):
        rep = params["scan_report"]
        return rep, str(rep.get("execution", {}).get("target") or params.get("target") or "inline"), None

    if params.get("findings") and isinstance(params["findings"], list):
        synthetic = {
            "tool_id": "inline_findings",
            "version": "0.0.0",
            "execution": {"target": params.get("target", "inline"), "status": "success"},
            "summary": {},
            "findings": params["findings"],
            "metadata": {},
        }
        return synthetic, str(params.get("target") or "inline"), None

    target = str(params.get("target") or params.get("input_file") or "").strip()
    if not target:
        return None, "", "missing target (path to scanner JSON, or scan_report/findings)"

    path = target
    if path.startswith("file://"):
        path = path[7:]
    # Windows-friendly strip only click scheme
    path = os.path.expanduser(path)
    if not os.path.isfile(path):
        return None, target, f"scan report file not found: {path}"
    try:
        # utf-8-sig strips PowerShell Set-Content BOM if present
        with open(path, "r", encoding="utf-8-sig") as f:
            rep = json.load(f)
    except Exception as e:
        return None, target, f"invalid JSON: {e}"
    if not isinstance(rep, dict):
        return None, target, "scan report root must be a JSON object"
    return rep, str(rep.get("execution", {}).get("target") or path), None


def _normalize_control_tokens(text: str) -> set[str]:
    stop = {
        "aws", "azure", "the", "and", "for", "with", "from", "that", "this",
        "not", "has", "have", "are", "is", "to", "of", "a", "an", "no", "on",
        "in", "or", "by", "be", "as", "at", "iam", "account", "enabled",
    }
    parts = re.sub(r"[^a-z0-9]+", " ", str(text or "").lower()).split()
    return {p for p in parts if len(p) > 2 and p not in stop}


def _titles_compatible(fix_name: str | None, finding_title: str | None) -> bool:
    """True when remediation template name and finding title refer to the same control."""
    if not fix_name or not finding_title:
        return True
    ta = _normalize_control_tokens(fix_name)
    tb = _normalize_control_tokens(finding_title)
    if not ta or not tb:
        return True
    overlap = len(ta & tb) / float(min(len(ta), len(tb)))
    return overlap >= 0.45


def _match_fix_by_title(title: str, description: str = "") -> str | None:
    """Resolve FIX_MAP key from finding title (exact name match preferred)."""
    blob = f"{title} {description}".strip()
    if not blob:
        return None
    title_l = title.strip().lower()
    # Exact FIX_MAP name match first
    for cid, fix in FIX_MAP.items():
        name = str(fix.get("name") or "").strip()
        if name and name.lower() == title_l:
            return cid
    # Token-compatible match among CLOUD-* (and others) — pick best overlap
    best_id = None
    best_score = 0.0
    tb = _normalize_control_tokens(blob)
    if not tb:
        return None
    for cid, fix in FIX_MAP.items():
        name = str(fix.get("name") or "")
        ta = _normalize_control_tokens(name)
        if not ta:
            continue
        score = len(ta & tb) / float(min(len(ta), len(tb)))
        if score > best_score:
            best_score = score
            best_id = cid
    if best_id and best_score >= 0.6:
        return best_id
    # Perimeter title map fallback
    for rx, gid in PERIM_TITLE_MAP:
        if rx.search(blob):
            return gid
    return None


def _content_looks_like_terraform(body: str) -> bool:
    text = body or ""
    if re.search(r'(?m)^\s*resource\s+"[^"]+"\s+"[^"]+"', text):
        return True
    if re.search(r'(?m)^\s*terraform\s*\{', text):
        return True
    if re.search(r'(?m)^\s*provider\s+"aws"', text):
        return True
    return False


def _control_family(check_id: str, category: str = "") -> str:
    cid = (check_id or "").upper()
    cat = (category or "").lower()
    if cid.startswith("PERIM-") or "perimeter" in cat:
        return "perimeter"
    if cid.startswith("CLOUD-IAM") or (cid.startswith("AWS-00") and "iam" in cat):
        return "iam"
    if "iam" in cat and not cid.startswith("CLOUD-STO"):
        return "iam"
    if cid.startswith("CLOUD-STO") or "storage" in cat or cat == "s3":
        return "storage"
    if cid.startswith("CLOUD-LOG") or "logging" in cat or "guardduty" in cat:
        return "logging"
    if cid.startswith("CLOUD-DFT") or "drift" in cat:
        return "drift"
    if cid.startswith("CLOUD-NET") or "network" in cat:
        return "network"
    if cid.startswith("DEVSEC"):
        return "devsecops"
    return "generic"


