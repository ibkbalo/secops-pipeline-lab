def run(params: dict) -> dict:
    started = _now()
    params = params or {}

    dry_run = params.get("dry_run", True)
    if dry_run is False:
        # Never auto-apply cloud changes in v1.0.0 — always kit-only.
        # apply mode is reserved for a future controlled actuation module.
        dry_run = True

    severity_threshold = str(params.get("severity_threshold") or "info").lower()
    if severity_threshold not in SEV_ORDER:
        severity_threshold = "info"

    max_runtime = int(params.get("max_runtime_seconds") or 300)
    output_dir = Path(str(params.get("output_dir") or "hardening_kits")).expanduser()

    report, target_label, err = _load_scan_report(params)
    if err:
        return _empty_report(target_label or "", "failed", err)

    findings_in = report.get("findings") or []
    if not isinstance(findings_in, list):
        return _empty_report(target_label, "failed", "scan report findings must be a list")

    source_tool = report.get("tool_id") or "unknown_scanner"
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    kit_name = f"kit_{_safe_name(source_tool)}_{stamp}"
    kit_root = output_dir / kit_name
    tf_dir = kit_root / "terraform"
    yml_dir = kit_root / "runbooks"
    conf_dir = kit_root / "configs"
    kit_root.mkdir(parents=True, exist_ok=True)
    tf_dir.mkdir(exist_ok=True)
    yml_dir.mkdir(exist_ok=True)
    conf_dir.mkdir(exist_ok=True)

    mapped = 0
    unmapped = 0
    artifacts = 0
    mapping_mismatches = 0
    out_findings = []
    fid = 0
    pick_log = []
    password_tf_written = False

    dup_names = detect_duplicate_fix_map_names()
    if dup_names:
        # Soft signal in kit; do not crash generation
        pick_log.append({"check_id": "FIX_MAP", "status": "duplicate_names", "detail": dup_names})

    for f in findings_in:
        if not isinstance(f, dict):
            continue
        sev = str(f.get("severity") or "info").lower()
        # Skip Passed Info checks from auditors
        if sev == "info":
            title = str(f.get("title") or "")
            if "PASSED" in title.upper() or (f.get("evidence") or {}).get("passed") is True:
                continue
        if not _threshold_ok(sev, severity_threshold):
            continue

        check_id = _resolve_check_id(f)
        fix = FIX_MAP.get(check_id)
        mismatch = _mapping_mismatch_reason(f, check_id, fix)
        if mismatch:
            # Refuse wrong template — do not emit root-MFA for password findings, etc.
            mapping_mismatches += 1
            fix = None
        resource = f.get("resource") or {}
        resource_id = str(resource.get("id") or target_label or "unknown")
        region = str(resource.get("region") or params.get("regions", ["us-east-1"])[0] if isinstance(params.get("regions"), list) else "us-east-1")
        account = str(resource.get("account") or resource.get("id") or "REPLACE_ACCOUNT")

        ctx = {
            "check_id": check_id,
            "name": (fix or {}).get("name") or f.get("title") or check_id,
            "title": f.get("title") or check_id,
            "severity": sev,
            "category": (fix or {}).get("category") or (f.get("evidence") or {}).get("category") or "general",
            "resource_id": resource_id,
            "region": region,
            "account": account,
            "description": (f.get("description") or "").replace("\n", " ").strip(),
            "version": VERSION,
        }
        ctx = _build_teaching_ctx(f, check_id, fix, ctx)

        written = []
        needs_review = False
        approval_ready = True

        if mismatch:
            needs_review = True
            approval_ready = False
            unmapped += 1
            yml_body = (
                f"# {check_id} — REMEDIATION_MAPPING_MISMATCH\n"
                f"# {mismatch}\n"
                f"# Finding title: {f.get('title')}\n"
                f"# This artifact is NOT approval-ready. Fix scanner/FIX_MAP alignment and regenerate.\n"
            )
            yml_path = yml_dir / f"{_safe_name(check_id or f.get('id') or 'MISMATCH')}_MAPPING_MISMATCH.yml"
            yml_path.write_text(yml_body, encoding="utf-8")
            written.append(str(yml_path.relative_to(kit_root)))
            artifacts += 1
            pick_log.append({
                "check_id": check_id,
                "status": "REMEDIATION_MAPPING_MISMATCH",
                "reason": mismatch,
                "files": written,
                "approval_ready": False,
            })
        elif fix:
            mapped += 1
            artifact = fix.get("artifact") or "runbook"
            pick_status = "mapped"
            # Terraform (password-policy family → one consolidated file)
            if artifact in ("terraform", "both") and fix.get("tf"):
                if check_id in PASSWORD_POLICY_CONTROL_IDS:
                    tf_path = tf_dir / PASSWORD_POLICY_TF_FILENAME
                    if not password_tf_written:
                        tf_ctx = dict(ctx)
                        tf_ctx["check_id"] = "CLOUD-IAM-001..005"
                        tf_ctx["name"] = "AWS IAM account password policy (consolidated)"
                        tf_path.write_text(_render(fix["tf"], tf_ctx), encoding="utf-8")
                        password_tf_written = True
                        artifacts += 1
                    written.append(str(tf_path.relative_to(kit_root)))
                else:
                    tf_body = _render(fix["tf"], ctx)
                    tf_path = tf_dir / f"{_safe_name(check_id)}.tf"
                    tf_path.write_text(tf_body, encoding="utf-8")
                    written.append(str(tf_path.relative_to(kit_root)))
                    artifacts += 1
            # Config / guidance fragments — never store Terraform HCL as primary .conf
            if fix.get("conf"):
                conf_body = _render(fix["conf"], ctx)
                type_mismatch = artifact_type_mismatch_reason(".conf", conf_body)
                if type_mismatch:
                    # Redirect HCL into terraform/ when no TF was already written for this control
                    tf_rel = f"terraform/{_safe_name(check_id)}.tf"
                    already_tf = any(str(w).replace("\\", "/").endswith(tf_rel) for w in written)
                    if not already_tf and _content_looks_like_terraform(conf_body):
                        tf_path = tf_dir / f"{_safe_name(check_id)}.tf"
                        tf_path.write_text(conf_body, encoding="utf-8")
                        written.append(str(tf_path.relative_to(kit_root)))
                        artifacts += 1
                    needs_review = True
                    approval_ready = False
                    pick_status = "ARTIFACT_TYPE_MISMATCH"
                    # Optional legacy pointer .conf (comments only) when body is not HCL
                    if not _content_looks_like_terraform(conf_body):
                        ext = ".txt" if "SECURITY-TXT" in check_id.upper() else ".conf"
                        conf_path = conf_dir / f"{_safe_name(check_id)}{ext}"
                        conf_path.write_text(conf_body, encoding="utf-8")
                        written.append(str(conf_path.relative_to(kit_root)))
                        artifacts += 1
                else:
                    ext = ".txt" if "SECURITY-TXT" in check_id.upper() else ".conf"
                    conf_path = conf_dir / f"{_safe_name(check_id)}{ext}"
                    conf_path.write_text(conf_body, encoding="utf-8")
                    written.append(str(conf_path.relative_to(kit_root)))
                    artifacts += 1
            # Runbook YAML
            if artifact in ("runbook", "both", "config") or not written:
                yml_body = _render(YML_GENERIC, ctx)
                rb_mismatch = runbook_control_mismatch_reason(
                    check_id,
                    str(ctx.get("category") or ""),
                    yml_body,
                    linked_files=list(ctx.get("_linked_files") or []),
                )
                if rb_mismatch:
                    needs_review = True
                    approval_ready = False
                    pick_status = "RUNBOOK_CONTROL_MISMATCH"
                    yml_body = (
                        f"# {check_id} — RUNBOOK_CONTROL_MISMATCH\n"
                        f"# {rb_mismatch}\n"
                        f"# Original teaching content retained below for diagnosis.\n"
                        f"{yml_body}"
                    )
                yml_path = yml_dir / f"{_safe_name(check_id)}.yml"
                yml_path.write_text(yml_body, encoding="utf-8")
                written.append(str(yml_path.relative_to(kit_root)))
                artifacts += 1
            pick_log.append({
                "check_id": check_id,
                "status": pick_status,
                "files": written,
                "fix_name": fix.get("name"),
                "finding_title": f.get("title"),
                "approval_ready": approval_ready,
                "needs_review": needs_review,
            })
        else:
            unmapped += 1
            needs_review = True
            approval_ready = False
            # Heuristic artifact: runbook from embedded remediation.steps
            yml_body = _render(YML_GENERIC, ctx)
            yml_path = yml_dir / f"{_safe_name(check_id or f.get('id') or 'UNMAPPED')}_UNMAPPED.yml"
            yml_path.write_text(yml_body, encoding="utf-8")
            written.append(str(yml_path.relative_to(kit_root)))
            artifacts += 1
            pick_log.append({"check_id": check_id, "status": "unmapped_runbook", "files": written, "approval_ready": False})

        fid += 1
        out_findings.append({
            "id": f"REM-{fid:03d}",
            "title": (
                f"REMEDIATION_MAPPING_MISMATCH for {check_id}"
                if mismatch
                else f"Hardening artifact generated for {check_id}" + (" (UNMAPPED — review)" if needs_review else "")
            ),
            "severity": sev if not needs_review else ("medium" if sev == "info" else sev),
            "confidence": "high" if fix and not mismatch else "low",
            "resource": {
                "type": "hardening_artifact",
                "id": check_id,
                "region": region,
            },
            "description": (
                mismatch
                or (
                    f"Created kit files for source finding '{f.get('id')}' "
                    f"({f.get('title')}). Mapped={bool(fix)}. dry_run={dry_run}."
                )
            ),
            "evidence": {
                "source_finding_id": f.get("id"),
                "source_tool_id": source_tool,
                "check_id": check_id,
                "mapped": bool(fix) and not mismatch,
                "mapping_mismatch": bool(mismatch),
                "approval_ready": approval_ready,
                "files": written,
                "fix_name": (fix or {}).get("name"),
            },
            "remediation": {
                "steps": [
                    f"Open kit files: {', '.join(written)}",
                    "Replace all REPLACE_* placeholders with real resource IDs.",
                    "Review in change window; apply via Terraform/console only after approval.",
                    "Re-run originating scanner to verify the control passes.",
                ],
                "effort": (fix or {}).get("effort") or "medium",
                "tier": 2,
                "reversible": True,
                "requires_approval": True,
            },
            "compliance": f.get("compliance") or [],
            "notes": (
                mismatch
                if mismatch
                else ("UNMAPPED — LLM or human should extend FIX_MAP" if needs_review else "")
            ),
        })

        # Respect max runtime (soft)
        if (_now() - started).total_seconds() > max_runtime:
            break

    # Manifest + README
    manifest = {
        "kit_name": kit_name,
        "generated_at": _ts(),
        "engine": {"tool_id": TOOL_ID, "version": VERSION},
        "source": {
            "tool_id": source_tool,
            "target": target_label,
            "risk_score": (report.get("summary") or {}).get("risk_score"),
        },
        "dry_run": dry_run,
        "severity_threshold": severity_threshold,
        "stats": {
            "input_findings": len(findings_in),
            "actionable_processed": mapped + unmapped,
            "mapped": mapped,
            "unmapped": unmapped,
            "mapping_mismatches": mapping_mismatches,
            "artifacts": artifacts,
        },
        "items": pick_log,
        "warning": (
            "This kit does NOT apply changes. Human approval required. "
            "Replace REPLACE_* placeholders before terraform apply. "
            "Items with REMEDIATION_MAPPING_MISMATCH are NOT approval-ready."
        ),
    }
    (kit_root / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    artifacts += 1

    readme = f"""# Sentinel Stacks — Hardening Kit

Generated: {manifest['generated_at']}
Source scanner: `{source_tool}`
Source target: `{target_label}`
Engine: `{TOOL_ID}` v{VERSION}

## What this is
A **teaching pack** for one scan job: every finding gets a runbook (what/why/how)
and often a config or Terraform sample. **Nothing auto-applies** to cloud or VPC.

**Finding ID = filename.** Example: Face shows `PERIM-DATA-001` → open
`runbooks/PERIM-DATA-001.yml` and `configs/PERIM-DATA-001.conf`.

## Layout
- `runbooks/` — YAML checklist per finding (`how_to_use`, `why_it_matters`, detailed steps)
- `configs/` — optional guidance fragments (perimeter may include nginx/WAF samples; Cloud prefers terraform/)
- `terraform/` — IaC remediation blueprints (primary for Cloud when present)
- `terraform/` — `.tf` blueprints (placeholders: `REPLACE_*`)
- `manifest.json` — machine index of generated items

## Stats
- Mapped controls: {mapped}
- Unmapped (review) controls: {unmapped}
- Artifacts: {artifacts}

## How to use (manager / engineer)
1. Start with **critical** then **high** findings (see Face or `manifest.json`).
2. For one finding ID, open its **runbook** first — read `how_to_use` and `why_it_matters`.
3. Open the matching **config** / **terraform** file listed under `linked_kit_files`.
4. Do `prechecks`, then `steps` (use `detail` for where/how). Replace `REPLACE_*`.
5. Run `validation` (re-scan). Confirm `success_looks_like`.
6. Approve in Face when you accept the plan — Approve still does **not** auto-apply.

## dry_run
This engine runs with dry_run=true. It never mutates customer environments.
"""
    (kit_root / "README.md").write_text(readme, encoding="utf-8")
    artifacts += 1

    zip_path = output_dir / f"{kit_name}.zip"
    _zip_dir(kit_root, zip_path)

    # summary counts from out_findings
    crit = sum(1 for x in out_findings if x["severity"] == "critical")
    high = sum(1 for x in out_findings if x["severity"] == "high")
    med = sum(1 for x in out_findings if x["severity"] == "medium")
    low = sum(1 for x in out_findings if x["severity"] == "low")
    info = sum(1 for x in out_findings if x["severity"] == "info")
    total = len(out_findings)
    duration = (_now() - started).total_seconds()

    if total == 0:
        status = "success"
        verdict = "No actionable findings at the requested severity threshold — empty kit shell created."
    elif unmapped and not mapped:
        status = "partial"
        verdict = f"Generated unmapped runbooks only ({unmapped}). Extend FIX_MAP or review manually."
    elif unmapped:
        status = "partial"
        verdict = f"Kit ready: {mapped} mapped, {unmapped} unmapped require human/LLM review."
    else:
        status = "success"
        verdict = f"Kit ready: {mapped} controls fully mapped to templates."

    llm = (
        f"Remediation Engine packaged hardening kit '{kit_name}' from '{source_tool}' "
        f"target '{target_label}'. Processed {mapped + unmapped} actionable findings "
        f"({mapped} mapped, {unmapped} unmapped). Wrote {artifacts} artifacts. "
        f"ZIP: {zip_path}. dry_run=True (no cloud mutation). {verdict}"
    )

    return {
        "tool_id": TOOL_ID,
        "version": VERSION,
        "execution": {
            "timestamp": _ts(),
            "duration_seconds": round(duration, 2),
            "target": target_label,
            "status": status,
            "error": None,
            "mode": "dry_run",
        },
        "summary": {
            "total_findings": total,
            "critical": crit,
            "high": high,
            "medium": med,
            "low": low,
            "info": info,
            "kits_generated": 1,
            "fixes_mapped": mapped,
            "fixes_unmapped": unmapped,
            "artifacts_written": artifacts,
        },
        "findings": out_findings,
        "metadata": {
            "domain": DOMAIN,
            "subdomain": SUBDOMAIN,
            "sentinel": SENTINEL,
            "tier": TIER,
            "tags": TAGS,
            "llm_summary": llm,
            "kit_path": str(zip_path),
            "kit_dir": str(kit_root),
            "dry_run": True,
            "source_tool_id": source_tool,
            "fix_map_size": len(FIX_MAP),
        },
    }


def remediate(input_path: str, output_dir: str = "hardening_kits") -> dict:
    return run({
        "target": input_path,
        "output_dir": output_dir,
        "dry_run": True,
        "severity_threshold": "info",
    })


