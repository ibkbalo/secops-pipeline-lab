def _artifact_extension(path_or_ext: str) -> str:
    """Normalize '.conf', 'conf', or 'foo.conf' to a dotted extension (Path('.conf') has no suffix)."""
    name = str(path_or_ext or "").strip().lower()
    if not name:
        return ""
    if name.startswith(".") and "/" not in name and "\\" not in name and name.count(".") == 1:
        return name  # bare extension like ".conf" / ".tf"
    suffix = Path(name).suffix.lower()
    if suffix:
        return suffix
    if name.startswith("."):
        return name
    return f".{name}" if name.isalpha() else ""


def artifact_type_mismatch_reason(path_or_ext: str, body: str) -> str | None:
    """Terraform HCL must not be stored as .conf (and similar mismatches)."""
    ext = _artifact_extension(path_or_ext)
    looks_tf = _content_looks_like_terraform(body)
    if ext == ".conf" and looks_tf:
        return (
            "ARTIFACT_TYPE_MISMATCH: Terraform HCL content cannot be the primary "
            "execution artifact under configs/*.conf — use terraform/*.tf"
        )
    if ext == ".tf" and body.strip() and not looks_tf and "LEGACY" not in body:
        # Allow comment-only pointer files only if explicitly legacy; otherwise mismatch
        if "resource " not in body and "aws_" in body.lower():
            return None
    return None


def runbook_control_mismatch_reason(
    check_id: str,
    category: str,
    runbook_text: str,
    *,
    linked_files: list[str] | None = None,
) -> str | None:
    """Reject runbooks that clearly leak another service's remediation template."""
    family = _control_family(check_id, category)
    text = runbook_text or ""
    for pat in _FAMILY_FORBIDDEN_PATTERNS.get(family, []):
        if pat.search(text):
            return (
                "RUNBOOK_CONTROL_MISMATCH: "
                f"runbook for {check_id} ({family}) contains incompatible term "
                f"matching /{pat.pattern}/ — not approval-ready"
            )
    # Linked artifact should share the same check_id when present
    for rel in linked_files or []:
        base = Path(str(rel)).name
        if base.startswith("CLOUD-") or base.startswith("PERIM-") or base.startswith("DEVSEC-"):
            linked_id = base.split(".")[0]
            if linked_id and linked_id != check_id and check_id not in linked_id:
                # Shared password TF is intentional
                if linked_id == "aws_iam_account_password_policy":
                    continue
                if check_id in PASSWORD_POLICY_CONTROL_IDS and "password_policy" in base:
                    continue
                return (
                    "RUNBOOK_CONTROL_MISMATCH: "
                    f"linked artifact {rel} does not match control {check_id}"
                )
    return None


def scan_cloud_kit_cross_service_leakage(kit_dir: str | Path) -> list[dict[str, str]]:
    """Lightweight report of obvious cross-service leakage in Cloud runbooks/configs."""
    root = Path(kit_dir)
    issues: list[dict[str, str]] = []
    rb_dir = root / "runbooks"
    if not rb_dir.is_dir():
        return issues
    for yml in sorted(rb_dir.glob("CLOUD-*.yml")):
        check_id = yml.stem
        text = yml.read_text(encoding="utf-8", errors="replace")
        # category hint from file
        cat = "Cloud/IAM" if check_id.startswith("CLOUD-IAM") else (
            "Cloud/Storage" if check_id.startswith("CLOUD-STO") else (
                "Cloud/Logging" if check_id.startswith("CLOUD-LOG") else (
                    "Cloud/Drift" if check_id.startswith("CLOUD-DFT") else "Cloud"
                )
            )
        )
        reason = runbook_control_mismatch_reason(check_id, cat, text)
        if reason:
            issues.append({"check_id": check_id, "file": str(yml), "reason": reason})
        for conf in (root / "configs").glob(f"{check_id}.*"):
            body = conf.read_text(encoding="utf-8", errors="replace")
            mismatch = artifact_type_mismatch_reason(conf.name, body)
            if mismatch:
                issues.append({"check_id": check_id, "file": str(conf), "reason": mismatch})
    return issues


