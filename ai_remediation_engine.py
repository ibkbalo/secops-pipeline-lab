def _load_scan_report(params: dict) -> tuple[dict | None, str, str | None]:
    """Return (report_dict, target_label, error)."""
    if params.get("scan_report") and isinstance(params["scan_report"], dict):
        rep = params["scan_report"]
        return rep, str(rep.get("execution", {}).get("target") or params.get("target") or "inline"), None

    if params.get("findings") and isinstance(params["findings"], list):
        synthetic = {
            "tool_id": "inline_findings",
            "version": "0.0.0",
            "execution": {"target": params.get("target", "inline"), "status": "success"},
            "summary": {},
            "findings": params["findings"],
            "metadata": {},
        }
        return synthetic, str(params.get("target") or "inline"), None

    target = str(params.get("target") or params.get("input_file") or "").strip()
    if not target:
        return None, "", "missing target (path to scanner JSON, or scan_report/findings)"

    path = target
    if path.startswith("file://"):
        path = path[7:]
    # Windows-friendly strip only click scheme
    path = os.path.expanduser(path)
    if not os.path.isfile(path):
        return None, target, f"scan report file not found: {path}"
    try:
        # utf-8-sig strips PowerShell Set-Content BOM if present
        with open(path, "r", encoding="utf-8-sig") as f:
            rep = json.load(f)
    except Exception as e:
        return None, target, f"invalid JSON: {e}"
    if not isinstance(rep, dict):
        return None, target, "scan report root must be a JSON object"
    return rep, str(rep.get("execution", {}).get("target") or path), None


def _resolve_check_id(finding: dict) -> str:
    """Map finding → stable FIX_MAP key (AWS/AZ/GOV/VULN/FIND/IDENT/DEVSEC/CLOUD/...)."""
    ev = finding.get("evidence") or {}
    if isinstance(ev, dict) and ev.get("check_id"):
        cid = str(ev["check_id"]).strip()
        if cid in FIX_MAP:
            return cid
        # still try title map if check_id unknown
    fid = str(finding.get("id") or "").strip()
    if fid in FIX_MAP:
        return fid

    title = str(finding.get("title") or "")
    desc = str(finding.get("description") or "")
    blob = f"{title} {desc}"

    # Sequential perimeter IDs (GOV-001, VULN-003, FIND-002, IDENT-010) → title map
    if re.match(r"^(GOV|VULN|FIND|IDENT|NET|DATA)-\d{3}$", fid, re.I) or not fid:
        for rx, gid in PERIM_TITLE_MAP:
            if rx.search(blob):
                return gid

    # Always try title map as secondary for any unmapped id
    if fid not in FIX_MAP:
        for rx, gid in PERIM_TITLE_MAP:
            if rx.search(blob):
                return gid

    # AWS/AZ sequential
    m = re.match(r"^(AWS|AZ)-(\d{3})$", fid, re.I)
    if m:
        return f"{m.group(1).upper()}-{m.group(2)}"
    return fid


def _threshold_ok(sev: str, threshold: str) -> bool:
    return _sev_rank(sev) >= _sev_rank(threshold) and sev.lower() in ACTIONABLE


def _render(template: str, ctx: dict) -> str:
    out = template
    for k, v in ctx.items():
        out = out.replace("{" + k + "}", str(v))
    return out


def _default_runbook_steps(finding: dict, check_id: str) -> list[str]:
    rem = finding.get("remediation") or {}
    steps = rem.get("steps") if isinstance(rem, dict) else None
    if steps:
        return list(steps)
    return [
        f"Open control {check_id}: {finding.get('title')}",
        finding.get("description") or "Apply CIS / vendor harden guidance.",
        "Re-scan with the originating Sentinel module to verify.",
    ]


def _zip_dir(src_dir: Path, zip_path: Path) -> None:
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(src_dir.rglob("*")):
            if p.is_file():
                zf.write(p, arcname=str(p.relative_to(src_dir)))


