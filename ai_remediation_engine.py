def _steps_block(steps: list[str]) -> str:
    if not steps:
        steps = ["Follow CIS / vendor documentation for this control."]
    lines = []
    for i, s in enumerate(steps, 1):
        clean = str(s).replace("\n", " ").strip()
        lines.append(f"    - step: {i}\n      action: |\n        {clean}")
    return "\n".join(lines)


