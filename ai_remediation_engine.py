def _indent_block(text: str, spaces: int = 4) -> str:
    pad = " " * spaces
    lines = (text or "").strip("\n").splitlines() or [""]
    return "\n".join(pad + (ln if ln.strip() else "") for ln in lines)


def _steps_block(steps: list) -> str:
    if not steps:
        steps = ["Follow CIS / vendor documentation for this control."]
    lines = []
    for i, s in enumerate(steps, 1):
        if isinstance(s, dict):
            action = str(s.get("action") or s.get("step") or "").replace("\n", " ").strip()
            detail = str(s.get("detail") or "").strip()
            why = str(s.get("why") or "").strip()
        else:
            action = str(s).replace("\n", " ").strip()
            detail = ""
            why = ""
        if not action:
            action = "Follow vendor hardening guidance for this control."
        chunk = [f"    - step: {i}", "      action: |", f"        {action}"]
        if detail:
            chunk.append("      detail: |")
            for ln in detail.splitlines() or [detail]:
                chunk.append(f"        {ln}")
        if why:
            chunk.append("      why: |")
            for ln in why.splitlines() or [why]:
                chunk.append(f"        {ln}")
        lines.append("\n".join(chunk))
    return "\n".join(lines)


def _default_how_to_use(
    check_id: str,
    has_conf: bool,
    has_tf: bool,
    category: str = "",
) -> str:
    parts = [
        f"1. Match this runbook to Face/Brain finding ID `{check_id}` (same ID = same issue).",
        "2. Read why_it_matters, then do prechecks — do not skip backups / change window.",
        "3. Work the steps in order. Each step may include detail (where/how) and why.",
    ]
    n = 4
    cat = (category or "").lower()
    cid = (check_id or "").upper()
    perimeter_like = cid.startswith("PERIM-") or "perimeter" in cat
    if has_tf:
        parts.append(
            f"{n}. Open `terraform/{check_id}.tf` for the IaC remediation — "
            "set the AWS provider Region to the finding Region, validate, plan, then "
            "human-triggered apply only after manager approval (platform does not auto-apply)."
        )
        n += 1
    if has_conf:
        if perimeter_like:
            parts.append(
                f"{n}. Open `configs/{check_id}.conf` for sample nginx/WAF rules — "
                "paste/adapt into your real edge; replace REPLACE_*."
            )
        else:
            parts.append(
                f"{n}. Open `configs/{check_id}.conf` only if present as supplementary "
                "guidance (not a Terraform execution artifact). Prefer terraform/ when linked."
            )
        n += 1
    parts.append(
        f"{n}. Run validation (re-scan / control API). Success = this check_id no longer fails."
    )
    n += 1
    parts.append(
        f"{n}. Approve in Face only after you understand the plan "
        "(Approve does not auto-apply)."
    )
    return "\n".join(parts)


