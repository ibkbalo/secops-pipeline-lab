def run(params: dict) -> dict:
    started = _now()
    params = params or {}

    dry_run = params.get("dry_run", True)
    if dry_run is False:
        # Never auto-apply cloud changes in v1.0.0 — always kit-only.
        # apply mode is reserved for a future controlled actuation module.
        dry_run = True

    severity_threshold = str(params.get("severity_threshold") or "info").lower()
    if severity_threshold not in SEV_ORDER:
        severity_threshold = "info"

    max_runtime = int(params.get("max_runtime_seconds") or 300)
    output_dir = Path(str(params.get("output_dir") or "hardening_kits")).expanduser()

    report, target_label, err = _load_scan_report(params)
    if err:
        return _empty_report(target_label or "", "failed", err)

    findings_in = report.get("findings") or []
    if not isinstance(findings_in, list):
        return _empty_report(target_label, "failed", "scan report findings must be a list")

    source_tool = report.get("tool_id") or "unknown_scanner"
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    kit_name = f"kit_{_safe_name(source_tool)}_{stamp}"
    kit_root = output_dir / kit_name
    tf_dir = kit_root / "terraform"
    yml_dir = kit_root / "runbooks"
    kit_root.mkdir(parents=True, exist_ok=True)
    tf_dir.mkdir(exist_ok=True)
    yml_dir.mkdir(exist_ok=True)

    mapped = 0
    unmapped = 0
    artifacts = 0
    out_findings = []
    fid = 0
    pick_log = []

    for f in findings_in:
        if not isinstance(f, dict):
            continue
        sev = str(f.get("severity") or "info").lower()
        # Skip Passed Info checks from auditors
        if sev == "info":
            title = str(f.get("title") or "")
            if "PASSED" in title.upper() or (f.get("evidence") or {}).get("passed") is True:
                continue
        if not _threshold_ok(sev, severity_threshold):
            continue

        check_id = _resolve_check_id(f)
        fix = FIX_MAP.get(check_id)
        resource = f.get("resource") or {}
        resource_id = str(resource.get("id") or target_label or "unknown")
        region = str(resource.get("region") or params.get("regions", ["us-east-1"])[0] if isinstance(params.get("regions"), list) else "us-east-1")
        account = str(resource.get("account") or resource.get("id") or "REPLACE_ACCOUNT")

        ctx = {
            "check_id": check_id,
            "name": (fix or {}).get("name") or f.get("title") or check_id,
            "title": f.get("title") or check_id,
            "severity": sev,
            "category": (fix or {}).get("category") or (f.get("evidence") or {}).get("category") or "general",
            "resource_id": resource_id,
            "region": region,
            "account": account,
            "description": f.get("description") or "",
            "version": VERSION,
            "steps_block": _steps_block(_default_runbook_steps(f, check_id)),
        }

        written = []
        needs_review = False

        if fix:
            mapped += 1
            artifact = fix.get("artifact") or "runbook"
            # Terraform
            if artifact in ("terraform", "both") and fix.get("tf"):
                tf_body = _render(fix["tf"], ctx)
                tf_path = tf_dir / f"{_safe_name(check_id)}.tf"
                tf_path.write_text(tf_body, encoding="utf-8")
                written.append(str(tf_path.relative_to(kit_root)))
                artifacts += 1
            # Runbook YAML
            if artifact in ("runbook", "both") or not written:
                yml_body = _render(YML_GENERIC, ctx)
                yml_path = yml_dir / f"{_safe_name(check_id)}.yml"
                yml_path.write_text(yml_body, encoding="utf-8")
                written.append(str(yml_path.relative_to(kit_root)))
                artifacts += 1
            pick_log.append({"check_id": check_id, "status": "mapped", "files": written})
        else:
            unmapped += 1
            needs_review = True
            # Heuristic artifact: runbook from embedded remediation.steps
            yml_body = _render(YML_GENERIC, ctx)
            yml_path = yml_dir / f"{_safe_name(check_id or f.get('id') or 'UNMAPPED')}_UNMAPPED.yml"
            yml_path.write_text(yml_body, encoding="utf-8")
            written.append(str(yml_path.relative_to(kit_root)))
            artifacts += 1
            pick_log.append({"check_id": check_id, "status": "unmapped_runbook", "files": written})

        fid += 1
        out_findings.append({
            "id": f"REM-{fid:03d}",
            "title": f"Hardening artifact generated for {check_id}" + (" (UNMAPPED — review)" if needs_review else ""),
            "severity": sev if not needs_review else ("medium" if sev == "info" else sev),
            "confidence": "high" if fix else "low",
            "resource": {
                "type": "hardening_artifact",
                "id": check_id,
                "region": region,
            },
            "description": (
                f"Created kit files for source finding '{f.get('id')}' "
                f"({f.get('title')}). Mapped={bool(fix)}. dry_run={dry_run}."
            ),
            "evidence": {
                "source_finding_id": f.get("id"),
                "source_tool_id": source_tool,
                "check_id": check_id,
                "mapped": bool(fix),
                "files": written,
                "fix_name": (fix or {}).get("name"),
            },
            "remediation": {
                "steps": [
                    f"Open kit files: {', '.join(written)}",
                    "Replace all REPLACE_* placeholders with real resource IDs.",
                    "Review in change window; apply via Terraform/console only after approval.",
                    "Re-run originating scanner to verify the control passes.",
                ],
                "effort": (fix or {}).get("effort") or "medium",
                "tier": 2,
                "reversible": True,
                "requires_approval": True,
            },
            "compliance": f.get("compliance") or [],
            "notes": "UNMAPPED — LLM or human should extend FIX_MAP" if needs_review else "",
        })

        # Respect max runtime (soft)
        if (_now() - started).total_seconds() > max_runtime:
            break

    # Manifest + README
    manifest = {
        "kit_name": kit_name,
        "generated_at": _ts(),
        "engine": {"tool_id": TOOL_ID, "version": VERSION},
        "source": {
            "tool_id": source_tool,
            "target": target_label,
            "risk_score": (report.get("summary") or {}).get("risk_score"),
        },
        "dry_run": dry_run,
        "severity_threshold": severity_threshold,
        "stats": {
            "input_findings": len(findings_in),
            "actionable_processed": mapped + unmapped,
            "mapped": mapped,
            "unmapped": unmapped,
            "artifacts": artifacts,
        },
        "items": pick_log,
        "warning": (
            "This kit does NOT apply changes. Human approval required. "
            "Replace REPLACE_* placeholders before terraform apply."
        ),
    }
    (kit_root / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    artifacts += 1

    readme = f"""# Sentinel Stacks — Hardening Kit

Generated: {manifest['generated_at']}
Source scanner: `{source_tool}`
Source target: `{target_label}`
Engine: `{TOOL_ID}` v{VERSION}

## What this is
Template fragments (Terraform + YAML runbooks) derived from scanner findings.
**The Kit is the Map. You are the Guide.** Nothing auto-applies to cloud.

## Layout
- `terraform/` — `.tf` blueprints (placeholders: REPLACE_*)
- `runbooks/` — step-by-step YAML per control
- `manifest.json` — machine index of generated items

## Stats
- Mapped controls: {mapped}
- Unmapped (review) controls: {unmapped}
- Artifacts: {artifacts}

## How to use
1. Review `manifest.json`
2. Edit placeholders in each file
3. Apply in a change window (Terraform plan → apply) **only after approval**
4. Re-run the originating Sentinel scanner
5. Archive this kit with ticket evidence

## dry_run
This engine runs with dry_run=true. It never calls AWS/Azure APIs to mutate state.
"""
    (kit_root / "README.md").write_text(readme, encoding="utf-8")
    artifacts += 1

    zip_path = output_dir / f"{kit_name}.zip"
    _zip_dir(kit_root, zip_path)

    # summary counts from out_findings
    crit = sum(1 for x in out_findings if x["severity"] == "critical")
    high = sum(1 for x in out_findings if x["severity"] == "high")
    med = sum(1 for x in out_findings if x["severity"] == "medium")
    low = sum(1 for x in out_findings if x["severity"] == "low")
    info = sum(1 for x in out_findings if x["severity"] == "info")
    total = len(out_findings)
    duration = (_now() - started).total_seconds()

    if total == 0:
        status = "success"
        verdict = "No actionable findings at the requested severity threshold — empty kit shell created."
    elif unmapped and not mapped:
        status = "partial"
        verdict = f"Generated unmapped runbooks only ({unmapped}). Extend FIX_MAP or review manually."
    elif unmapped:
        status = "partial"
        verdict = f"Kit ready: {mapped} mapped, {unmapped} unmapped require human/LLM review."
    else:
        status = "success"
        verdict = f"Kit ready: {mapped} controls fully mapped to templates."

    llm = (
        f"Remediation Engine packaged hardening kit '{kit_name}' from '{source_tool}' "
        f"target '{target_label}'. Processed {mapped + unmapped} actionable findings "
        f"({mapped} mapped, {unmapped} unmapped). Wrote {artifacts} artifacts. "
        f"ZIP: {zip_path}. dry_run=True (no cloud mutation). {verdict}"
    )

    return {
        "tool_id": TOOL_ID,
        "version": VERSION,
        "execution": {
            "timestamp": _ts(),
            "duration_seconds": round(duration, 2),
            "target": target_label,
            "status": status,
            "error": None,
            "mode": "dry_run",
        },
        "summary": {
            "total_findings": total,
            "critical": crit,
            "high": high,
            "medium": med,
            "low": low,
            "info": info,
            "kits_generated": 1,
            "fixes_mapped": mapped,
            "fixes_unmapped": unmapped,
            "artifacts_written": artifacts,
        },
        "findings": out_findings,
        "metadata": {
            "domain": DOMAIN,
            "subdomain": SUBDOMAIN,
            "sentinel": SENTINEL,
            "tier": TIER,
            "tags": TAGS,
            "llm_summary": llm,
            "kit_path": str(zip_path),
            "kit_dir": str(kit_root),
            "dry_run": True,
            "source_tool_id": source_tool,
            "fix_map_size": len(FIX_MAP),
        },
    }


def remediate(input_path: str, output_dir: str = "hardening_kits") -> dict:
    return run({
        "target": input_path,
        "output_dir": output_dir,
        "dry_run": True,
        "severity_threshold": "info",
    })


